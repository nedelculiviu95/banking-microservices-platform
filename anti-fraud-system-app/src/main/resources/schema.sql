CREATE TABLE user_account (
    user_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50),
    password VARCHAR(100),
    name     VARCHAR(50),
    role     VARCHAR(50),
    creation_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE ip (
    ip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_val VARCHAR(50),
    creation_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE stolen_card (
    stolen_card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stolen_card_number VARCHAR(50),
    creation_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);